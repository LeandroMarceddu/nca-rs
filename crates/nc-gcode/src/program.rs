//! Parsed program, its lines, and aggregate statistics.

use std::ops::Range;

use nc_core::{Position, math};
use nc_viewer::{Bounds3, MoveKind, Toolpath};

use crate::error::ParseWarning;
use crate::expression::Parameters;
use crate::lexer::Word;
use crate::motion::{Annotation, CannedRecord, Comment, ModalId, ModalState, MotionRecord};
use crate::state::ParserState;

/// One source line together with its lexed words and generated geometry.
#[derive(Debug, Clone, PartialEq)]
pub struct ProgramLine {
    /// 1-based line number in the source program.
    pub line: usize,
    /// The `N` word line number, when the line has one.
    pub number: Option<u32>,
    /// Original source text without the terminator or a UTF-8 BOM.
    pub source: String,
    /// Words in source order, including `N`, `G`, and `M`.
    pub words: Vec<Word>,
    /// Comment text without delimiters, in source order.
    pub comments: Vec<String>,
    /// `true` when the line carried the `/` block-delete marker.
    ///
    /// The geometry is still generated: whether the controller executes the
    /// block depends on its block-delete switch at run time.
    pub block_delete: bool,
    /// The `*` checksum value, when one was present and valid.
    pub checksum: Option<u8>,
    /// Range of toolpath segments generated by this block.
    ///
    /// Empty for modal-only, comment, and blank lines. The range indexes the
    /// [`Program::toolpath`] segment stream.
    pub segments: Range<usize>,
}

impl ProgramLine {
    /// Returns `true` when the line has at least one word.
    #[must_use]
    pub fn has_words(&self) -> bool {
        !self.words.is_empty()
    }

    /// Returns `true` when the line has no words and no comments.
    #[must_use]
    pub fn is_blank(&self) -> bool {
        self.words.is_empty() && self.comments.is_empty() && !self.block_delete
    }

    /// Number of toolpath segments generated by this block.
    #[must_use]
    pub fn segment_count(&self) -> usize {
        self.segments.len()
    }
}

/// Aggregate statistics for a parsed program.
///
/// Lengths are the displayed toolpath lengths in millimetres. Arc lengths are
/// exact (radius times sweep), not the sum of chord approximations. Feed times
/// and acceleration are intentionally not modelled.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct ProgramStats {
    /// Source lines, including blank and comment-only lines.
    pub lines: usize,
    /// Lines with at least one word.
    pub blocks: usize,
    /// Total words across all lines.
    pub words: usize,
    /// Toolpath segments (arc chords included).
    pub segments: usize,
    /// Rapid segments.
    pub rapid_segments: usize,
    /// Feed segments.
    pub feed_segments: usize,
    /// Vertical entry (plunge) segments.
    pub plunge_segments: usize,
    /// Arc chord segments.
    pub arc_segments: usize,
    /// Probe segments.
    pub probe_segments: usize,
    /// Blocks that commanded an arc (`G2`/`G3`).
    pub arc_moves: usize,
    /// Blocks that ran a canned cycle.
    pub canned_cycles: usize,
    /// Blocks that commanded a tool change (`M6`).
    pub tool_changes: usize,
    /// Total path length in millimetres.
    pub path_length_mm: f64,
    /// Rapid path length in millimetres.
    pub rapid_length_mm: f64,
    /// Cutting path length in millimetres (feed, plunge, and arc).
    pub cutting_length_mm: f64,
    /// Tool numbers that produced geometry or were selected by a `T` word,
    /// sorted and deduplicated.
    pub tools: Vec<u32>,
    /// Lowest programmed feed in millimetres per minute, when known.
    pub min_feed_mm_per_min: Option<f64>,
    /// Highest programmed feed in millimetres per minute, when known.
    pub max_feed_mm_per_min: Option<f64>,
    /// Highest programmed spindle speed in revolutions per minute.
    pub max_spindle_rpm: f64,
}

impl ProgramStats {
    /// Records a programmed feed that uses millimetres per minute.
    pub(crate) fn observe_feed(&mut self, feed_mm_per_min: f64) {
        if !feed_mm_per_min.is_finite() || feed_mm_per_min < 0.0 {
            return;
        }
        self.min_feed_mm_per_min = Some(match self.min_feed_mm_per_min {
            Some(current) => current.min(feed_mm_per_min),
            None => feed_mm_per_min,
        });
        self.max_feed_mm_per_min = Some(match self.max_feed_mm_per_min {
            Some(current) => current.max(feed_mm_per_min),
            None => feed_mm_per_min,
        });
    }

    /// Records a tool number that produced geometry.
    pub(crate) fn observe_tool(&mut self, tool: u32) {
        if let Err(index) = self.tools.binary_search(&tool) {
            self.tools.insert(index, tool);
        }
    }
}

/// A validated program with its display geometry.
#[derive(Debug, Clone, PartialEq)]
pub struct Program {
    /// Source lines in order.
    pub lines: Vec<ProgramLine>,
    /// Display toolpath in machine/display millimetres.
    ///
    /// Every segment uses layer 0 and the tool number that was active for the
    /// move. See the [`Parser`](crate::Parser) docs for the coordinate
    /// transform that is applied.
    pub toolpath: Toolpath,
    /// Axis-aligned bounds of [`Program::toolpath`].
    ///
    /// Arc bounds are exact and include the full circle extents, even when the
    /// stored tessellation is coarser.
    pub bounds: Bounds3,
    /// Aggregate statistics.
    pub stats: ProgramStats,
    /// Modal state after the last line.
    pub state: ParserState,
    /// `#` parameter table after the last line.
    ///
    /// Assignments are committed per validated block, so this is the table a
    /// controller would hold after running the program.
    pub parameters: Parameters,
    /// Work coordinate offsets in `G54`..`G59.3` order at the end of the
    /// program, including any `G10` changes, in millimetres.
    pub offsets: [Position; 9],
    /// Non-fatal issues found while parsing.
    pub warnings: Vec<ParseWarning>,
    /// Machine-coordinate motion records in program order.
    pub motions: Vec<MotionRecord>,
    /// Non-motion events in program order.
    pub annotations: Vec<Annotation>,
    /// Every source comment with its line.
    pub comments: Vec<Comment>,
    /// Best-effort tool data recovered from comments.
    pub tool_hints: Vec<nc_core::ToolHint>,
    /// Interned modal states referenced by [`MotionRecord::modal`].
    pub modal_table: Vec<ModalState>,
    /// First line after which new geometry is not trusted.
    pub geometry_uncertain_after_line: Option<usize>,
}

impl Program {
    /// Returns `true` when the program produced no geometry.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.toolpath.is_empty()
    }

    /// Number of toolpath segments.
    #[must_use]
    pub fn segment_count(&self) -> usize {
        self.toolpath.len()
    }

    /// Finds the source line that generated `segment`.
    ///
    /// Returns `None` when the index is out of range or falls in a gap between
    /// lines.
    #[must_use]
    pub fn line_for_segment(&self, segment: usize) -> Option<&ProgramLine> {
        if segment >= self.toolpath.len() {
            return None;
        }
        let index = self
            .lines
            .partition_point(|line| line.segments.end <= segment);
        self.lines
            .get(index)
            .filter(|line| line.segments.contains(&segment))
    }

    /// Axis-aligned bounds of cutting moves only.
    ///
    /// Feed, plunge, ramp, arc, helix, drill, peck, and bore moves contribute;
    /// rapids and retracts do not, so a safe-Z rapid never inflates inferred
    /// stock. Arc extents and canned-cycle bottoms are exact. Returns
    /// [`Bounds3::empty`] when the program has no cutting move.
    #[must_use]
    pub fn cutting_bounds(&self) -> Bounds3 {
        let mut bounds = Bounds3::empty();
        if self.motions.is_empty() {
            for segment in self.toolpath.segments() {
                if segment.kind.is_cutting() {
                    bounds.expand(segment.start);
                    bounds.expand(segment.end);
                }
            }
            return bounds;
        }
        for motion in &self.motions {
            if !motion.kind.is_cutting() {
                continue;
            }
            if let Some(canned) = &motion.canned {
                // The hole XY is the record's end; the cutting extent runs from
                // the R plane to the bottom. The initial/retract level is a
                // rapid and must not inflate inferred stock.
                bounds.expand(point([
                    motion.end_mm[0],
                    motion.end_mm[1],
                    canned.bottom_z_mm,
                ]));
                bounds.expand(point([
                    motion.end_mm[0],
                    motion.end_mm[1],
                    canned.r_plane_mm,
                ]));
                continue;
            }
            bounds.expand(point(motion.start_mm));
            match &motion.arc {
                Some(arc) => visit_arc_extents(motion, arc, |extent| bounds.expand(point(extent))),
                None => bounds.expand(point(motion.end_mm)),
            }
        }
        bounds
    }

    /// Returns the interned modal state for `id`.
    ///
    /// An out-of-range id returns a conservative unknown state instead of
    /// panicking; ids come from the parser, but reports may be loaded from
    /// untrusted JSON.
    #[must_use]
    pub fn modal(&self, id: ModalId) -> &ModalState {
        static FALLBACK: ModalState = ModalState::UNKNOWN;
        self.modal_table.get(id.0 as usize).unwrap_or(&FALLBACK)
    }

    /// First line after which new geometry is not trusted, if any.
    #[must_use]
    pub fn geometry_uncertain_after(&self) -> Option<usize> {
        self.geometry_uncertain_after_line
    }

    /// Expands canned-cycle records into their rapid/feed/retract sub-moves.
    ///
    /// The expansion is generated on demand; the program stores one record per
    /// hole. The simulator and timeline consume this iterator.
    pub fn expanded_motions(&self) -> impl Iterator<Item = MotionRecord> + '_ {
        ExpandedMotions {
            motions: &self.motions,
            next: 0,
            pending: Vec::new().into_iter(),
            canned_run: None,
        }
    }
}

/// Iterator over real motions with canned cycles expanded on demand.
struct ExpandedMotions<'a> {
    motions: &'a [MotionRecord],
    next: usize,
    pending: std::vec::IntoIter<MotionRecord>,
    canned_run: Option<(crate::state::CannedCycleKind, f64)>,
}

impl Iterator for ExpandedMotions<'_> {
    type Item = MotionRecord;

    fn next(&mut self) -> Option<Self::Item> {
        loop {
            if let Some(motion) = self.pending.next() {
                return Some(motion);
            }
            let record = self.motions.get(self.next)?;
            self.next += 1;
            match &record.canned {
                Some(canned) => {
                    let initial_z = match self.canned_run {
                        Some((cycle, initial_z))
                            if cycle == canned.cycle && canned.hole_index > 0 =>
                        {
                            initial_z
                        }
                        _ => record.start_mm[2],
                    };
                    self.canned_run = Some((canned.cycle, initial_z));
                    self.pending = expand_canned(record, canned, initial_z).into_iter();
                }
                None => {
                    self.canned_run = None;
                    return Some(record.clone());
                }
            }
        }
    }
}

/// Upper bound on sub-moves generated for one pecked hole.
///
/// The planner already rejects programs that need more pecks; this bound keeps
/// `expanded_motions` safe on a hand-built or deserialized `Program` too.
const MAX_EXPANDED_PECKS: u64 = 10_000;

/// Generates the sub-moves of one canned-cycle hole.
fn expand_canned(
    record: &MotionRecord,
    canned: &CannedRecord,
    initial_z: f64,
) -> Vec<MotionRecord> {
    let [x, y, start_z] = record.start_mm;
    let r = canned.r_plane_mm;
    let bottom = canned.bottom_z_mm.min(r);
    let retract_z = match canned.retract_mode {
        crate::state::RetractMode::RPlane => r,
        crate::state::RetractMode::Initial => initial_z.max(r),
    };
    let mut out = Vec::new();
    let mut push = |kind: MoveKind, start: [f64; 3], end: [f64; 3]| {
        let mut sub = record.clone();
        sub.kind = kind;
        sub.start_mm = start;
        sub.end_mm = end;
        sub.arc = None;
        sub.canned = None;
        out.push(sub);
    };

    let mut current = [x, y, start_z];
    if canned.retract_mode == crate::state::RetractMode::RPlane {
        if math::abs(current[2] - r) > 1e-9 {
            push(MoveKind::Rapid, current, [x, y, r]);
            current = [x, y, r];
        }
    } else if math::abs(current[2] - retract_z) > 1e-9 {
        push(MoveKind::Rapid, current, [x, y, retract_z]);
        current = [x, y, retract_z];
    }

    let travel_z = current[2];
    let hole = [record.end_mm[0], record.end_mm[1]];
    if math::abs(current[0] - hole[0]) > 1e-9 || math::abs(current[1] - hole[1]) > 1e-9 {
        push(MoveKind::Rapid, current, [hole[0], hole[1], travel_z]);
        current = [hole[0], hole[1], travel_z];
    }

    if current[2] > r {
        push(MoveKind::Rapid, current, [hole[0], hole[1], r]);
        current = [hole[0], hole[1], r];
    }

    let down_kind = match canned.cycle {
        crate::state::CannedCycleKind::ChipBreak | crate::state::CannedCycleKind::PeckDrill => {
            MoveKind::Peck
        }
        crate::state::CannedCycleKind::BoreFeedOut
        | crate::state::CannedCycleKind::BoreStop
        | crate::state::CannedCycleKind::BoreDwell => MoveKind::Bore,
        _ => MoveKind::Drill,
    };

    let has_material = bottom < r;
    if has_material {
        match canned.cycle {
            crate::state::CannedCycleKind::ChipBreak | crate::state::CannedCycleKind::PeckDrill => {
                let q = canned.peck_q_mm.unwrap_or(r - bottom);
                let q = if q > 0.0 { q } else { r - bottom };
                let mut z = r;
                let mut pecks = 0u64;
                let reached = loop {
                    pecks = pecks.saturating_add(1);
                    let next = math::clamp(z - q, bottom, r);
                    push(down_kind, [hole[0], hole[1], z], [hole[0], hole[1], next]);
                    if next <= bottom + 1e-9 || pecks >= MAX_EXPANDED_PECKS {
                        break next;
                    }
                    let break_z = if canned.cycle == crate::state::CannedCycleKind::PeckDrill {
                        r
                    } else {
                        (next + q).min(r)
                    };
                    if break_z > next {
                        push(
                            MoveKind::Rapid,
                            [hole[0], hole[1], next],
                            [hole[0], hole[1], break_z],
                        );
                        push(
                            MoveKind::Rapid,
                            [hole[0], hole[1], break_z],
                            [hole[0], hole[1], next],
                        );
                    }
                    z = next;
                };
                current = [hole[0], hole[1], reached];
            }
            crate::state::CannedCycleKind::BoreFeedOut
            | crate::state::CannedCycleKind::BoreDwell => {
                push(down_kind, [hole[0], hole[1], r], [hole[0], hole[1], bottom]);
                push(down_kind, [hole[0], hole[1], bottom], [hole[0], hole[1], r]);
                current = [hole[0], hole[1], r];
            }
            crate::state::CannedCycleKind::BoreStop => {
                push(down_kind, [hole[0], hole[1], r], [hole[0], hole[1], bottom]);
                push(
                    MoveKind::Retract,
                    [hole[0], hole[1], bottom],
                    [hole[0], hole[1], r],
                );
                current = [hole[0], hole[1], r];
            }
            _ => {
                push(down_kind, [hole[0], hole[1], r], [hole[0], hole[1], bottom]);
                current = [hole[0], hole[1], bottom];
            }
        }
    }

    if math::abs(current[2] - retract_z) > 1e-9 {
        if retract_z > current[2] {
            push(MoveKind::Retract, current, [hole[0], hole[1], retract_z]);
        } else {
            push(MoveKind::Rapid, current, [hole[0], hole[1], retract_z]);
        }
    }
    out
}

/// Visits the exact extreme points of an arc in machine coordinates.
fn visit_arc_extents(
    motion: &MotionRecord,
    arc: &crate::motion::ArcRecord,
    mut visit: impl FnMut([f64; 3]),
) {
    visit(motion.start_mm);
    visit(motion.end_mm);
    let (u, v) = motion.plane.axes();
    let normal = motion.plane.normal_axis();
    let total = math::abs(arc.sweep_rad);
    if total <= 0.0 || !arc.radius_mm.is_finite() {
        return;
    }
    for cardinal in [0.0, math::FRAC_PI_2, math::PI, math::PI + math::FRAC_PI_2] {
        let traveled = if arc.sweep_rad >= 0.0 {
            cardinal - arc.start_angle_rad
        } else {
            arc.start_angle_rad - cardinal
        }
        .rem_euclid(math::TAU);
        if traveled <= 1e-12 || traveled >= total - 1e-12 {
            continue;
        }
        let mut point = [0.0; 3];
        point[u] = arc.center_mm[u] + arc.radius_mm * math::cos(cardinal);
        point[v] = arc.center_mm[v] + arc.radius_mm * math::sin(cardinal);
        let fraction = traveled / total;
        point[normal] =
            motion.start_mm[normal] + (motion.end_mm[normal] - motion.start_mm[normal]) * fraction;
        visit(point);
    }
}

/// Converts f64 machine coordinates into the viewer's f32 point.
fn point(value: [f64; 3]) -> nc_viewer::Point3 {
    nc_viewer::Point3::new(value[0] as f32, value[1] as f32, value[2] as f32)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tools_are_sorted_and_unique() {
        let mut stats = ProgramStats::default();
        for tool in [3, 1, 3, 2] {
            stats.observe_tool(tool);
        }
        assert_eq!(stats.tools, vec![1, 2, 3]);
    }

    #[test]
    fn feed_range_is_tracked() {
        let mut stats = ProgramStats::default();
        assert_eq!(stats.min_feed_mm_per_min, None);
        stats.observe_feed(100.0);
        stats.observe_feed(50.0);
        assert_eq!(stats.min_feed_mm_per_min, Some(50.0));
        assert_eq!(stats.max_feed_mm_per_min, Some(100.0));
        stats.observe_feed(f64::NAN);
        stats.observe_feed(-1.0);
        assert_eq!(stats.min_feed_mm_per_min, Some(50.0));
    }
}
